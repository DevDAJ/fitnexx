export interface FoodInfo {
  label: FoodLabel;
  name: string;
  kcalPer100: number;
  proteinPer100: number;
  carbsPer100: number;
  fatPer100: number;
  defaultServingG: number;
}

const INFO_BY_INDEX: readonly FoodInfo[] = FOOD_LABELS.map((label) => {
  const [calories, protein, carbs, fat, servingG] = FOOD_ROWS[label];
  const name = label.split("_").join(" ");
  return {
    label,
    name: name.charAt(0).toUpperCase() + name.slice(1),
    kcalPer100: calories,
    proteinPer100: protein,
    carbsPer100: carbs,
    fatPer100: fat,
    defaultServingG: servingG,
  };
});

export function foodInfoAt(index: number): FoodInfo | undefined {
  return INFO_BY_INDEX[index];
}

export function macrosForServing(
  label: FoodLabel,
  grams: number,
): { calories: number; protein: number; carbs: number; fat: number } {
  const row = FOOD_ROWS[label];
  const scale = grams / 100;
  return {
    calories: Math.round(row[0] * scale),
    protein: Math.round(row[1] * scale),
    carbs: Math.round(row[2] * scale),
    fat: Math.round(row[3] * scale),
  };
}
